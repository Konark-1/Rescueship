/**
 * RescueShip operator setup — one command instead of hunting through dashboards.
 *
 *   npm run setup                         → writes .env.render.local + .env.netlify.local
 *                                            (bulk-paste into Render / Netlify) and prints
 *                                            the remaining clicks, in order.
 *   npm run setup -- --check [api url]    → asks the live API what is still missing
 *                                            (uses OPS_API_KEY from .env.render.local).
 *
 * Both files are git-ignored (.env.*). Existing values are kept on re-runs, so the
 * secrets you already pasted into Meta/Razorpay never change under you.
 * JWT_SECRET / ENCRYPTION_KEY are NOT generated: they already exist on Render and
 * changing ENCRYPTION_KEY would lock every merchant out of their saved connections.
 */
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import axios from 'axios';

const ROOT = path.resolve(__dirname, '..');
const RENDER_FILE = path.join(ROOT, '.env.render.local');
const NETLIFY_FILE = path.join(ROOT, '.env.netlify.local');

const API = 'https://rescueship.onrender.com';
const WEB = 'https://rescueship.netlify.app';
const META_APP_ID = '1077746595167424';

function readEnv(file: string): Record<string, string> {
  if (!fs.existsSync(file)) return {};
  const out: Record<string, string> = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function writeEnv(file: string, header: string, values: Record<string, string>) {
  const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
  fs.writeFileSync(file, `# ${header}\n# Generated by npm run setup — do NOT commit (git-ignored).\n${body}\n`, { mode: 0o600 });
}

const secret = (bytes = 24) => crypto.randomBytes(bytes).toString('hex');

function generate() {
  const prev = readEnv(RENDER_FILE);
  const render: Record<string, string> = {
    API_PUBLIC_URL: prev.API_PUBLIC_URL || API,
    API_BASE_URL: prev.API_BASE_URL || API,
    FRONTEND_URL: prev.FRONTEND_URL || WEB,
    APP_URL: prev.APP_URL || WEB,
    META_APP_ID: prev.META_APP_ID || META_APP_ID,
    META_CONFIG_ID: prev.META_CONFIG_ID || '',
    OPS_API_KEY: prev.OPS_API_KEY || secret(24),
    OPS_ALERT_EMAIL: prev.OPS_ALERT_EMAIL || 'konarkofficial@gmail.com',
    WHATSAPP_VERIFY_TOKEN: prev.WHATSAPP_VERIFY_TOKEN || `rs_verify_${secret(12)}`,
    RAZORPAY_WEBHOOK_SECRET: prev.RAZORPAY_WEBHOOK_SECRET || secret(20),
    FREE_TEST_ENABLED: prev.FREE_TEST_ENABLED || 'true',
  };
  writeEnv(RENDER_FILE, 'Render → rescueship → Environment → "Add from .env" → paste this whole file', render);

  const prevN = readEnv(NETLIFY_FILE);
  const netlify: Record<string, string> = {
    VITE_META_APP_ID: prevN.VITE_META_APP_ID || META_APP_ID,
    VITE_META_CONFIG_ID: prevN.VITE_META_CONFIG_ID || render.META_CONFIG_ID || '',
  };
  writeEnv(NETLIFY_FILE, 'Netlify → rescueship → Site configuration → Environment variables → Import from .env', netlify);

  const steps = [
    ['Render', `Open ${'https://dashboard.render.com'} → rescueship → Environment → "Add from .env" → paste .env.render.local → Save. Also paste META_APP_SECRET yourself (Meta → App settings → Basic).`],
    ['Netlify', 'Site configuration → Environment variables → Import from .env → paste .env.netlify.local → redeploy.'],
    ['Meta webhook', `(If you already verified the Meta webhook with an older token, keep that token: put it in WHATSAPP_VERIFY_TOKEN in .env.render.local before pasting.) WhatsApp → Configuration → Edit webhook: Callback URL ${API}/webhooks/whatsapp · Verify token = WHATSAPP_VERIFY_TOKEN from .env.render.local → Verify and save → subscribe "messages".`],
    ['Meta one-click signup', 'Facebook Login for Business → Configurations → Create → "WhatsApp Embedded Signup" → copy the id into META_CONFIG_ID (both files) → re-run npm run setup → paste again.'],
    ['Razorpay webhook', `Account & Settings → Webhooks → Add: URL ${API}/webhooks/razorpay/payment · Secret = RAZORPAY_WEBHOOK_SECRET · events: payment.captured, payment.failed, subscription.* → Save.`],
    ['Shopify app', 'In this folder: npx @shopify/cli@latest app deploy (log in with the Shopify Partner account) → confirm.'],
    ['Check', 'npm run setup -- --check   (lists anything still missing)'],
  ];
  console.log('\n✔ Wrote .env.render.local and .env.netlify.local (git-ignored; values not printed).\n');
  steps.forEach(([t, s], i) => console.log(`${i + 1}. ${t}\n   ${s}\n`));
}

async function check(apiArg?: string) {
  const api = (apiArg || API).replace(/\/$/, '');
  const key = process.env.OPS_API_KEY || readEnv(RENDER_FILE).OPS_API_KEY;
  if (!key) {
    console.error('No OPS_API_KEY. Run `npm run setup` and paste .env.render.local into Render first.');
    process.exit(2);
  }
  let data: any;
  try {
    data = (await axios.get(`${api}/api/liveops/setup-status`, { headers: { 'x-ops-key': key }, timeout: 70000 })).data;
  } catch (e: any) {
    const st = e.response?.status;
    console.error(st === 401
      ? 'The live API rejected the ops key — paste .env.render.local into Render and wait for the redeploy.'
      : st === 404 ? 'The live API is still on the old code — merge the pull request so Render redeploys.'
      : `Could not reach ${api}: ${e.message}`);
    process.exit(1);
  }
  const icon: Record<string, string> = { ok: '✅', missing: '❌', waiting: '⏳', optional: '◽' };
  let area = '';
  for (const it of data.items) {
    if (it.area !== area) { area = it.area; console.log(`\n${area}`); }
    console.log(`  ${icon[it.state] || '•'} ${it.label}${it.detail ? ` — ${it.detail}` : ''}`);
    if (it.fix && it.state !== 'ok') console.log(`       → ${it.fix}`);
  }
  console.log(`\n${data.summary.ok} done · ${data.summary.missing} missing · ${data.summary.waiting} waiting · merchants ${data.merchants.total} (${data.merchants.paying} paying)`);
  console.log(data.ready ? '\n🎉 Everything is set up.' : '\nFix the ❌ items first; ⏳ items turn green once the first real event arrives.');
  process.exit(data.ready ? 0 : 1);
}

const args = process.argv.slice(2);
if (args[0] === '--check') check(args[1]);
else generate();
